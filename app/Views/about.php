    <p class="eyebrow">SOBRE O CIDADECOLABORATIVA</p>
    <h1>Participação que aproxima.</h1>
    <p class="lead">Uma plataforma acadêmica para transformar relatos dispersos em informação acessível sobre nossa cidade.</p>
    <h2>Por que este projeto existe?</h2>
    <p>Buracos, iluminação, resíduos e outros problemas urbanos são frequentemente relatados em grupos e redes sociais. A proposta é organizar essas informações e permitir que moradores de Rio do Sul consultem e acompanhem relatos em um único lugar.</p>
    <h2>Como funciona</h2>
    <ol>
        <li>Um cidadão registra o problema com localização e fotografias.</li>
        <li>A equipe modera o conteúdo e pode solicitar correções.</li>
        <li>Após aprovação, o relato aparece no mapa e na listagem pública.</li>
        <li>A comunidade confirma, sinaliza problemas e sugere resoluções.</li>
    </ol>
    <h2>Compromisso acadêmico</h2>
    <p>Projeto de extensão da disciplina Programação Web I, Sistemas de Informação, UNIDAVI. O desenvolvimento prioriza PHP, organização MVC e segurança no servidor. Entrevistas e validação com interessados ainda dependem da realização efetiva pelo grupo.</p>
    <h2>O que a plataforma não faz</h2>
    <p>Não representa a prefeitura ou a Defesa Civil, não abre chamados oficiais e não prevê enchentes. A situação “em acompanhamento” indica acompanhamento pela plataforma.</p><a class="btn btn-primary" href="<?= e(url('/mapa')) ?>">Conhecer o mapa</a>
